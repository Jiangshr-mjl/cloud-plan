import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {chromium} from 'playwright';
import {applyOperation,beijingDate} from '../lib/planner.ts';
const browser=await chromium.launch({channel:'msedge'});
try {for(const width of [1360,390]) {
  const page=await browser.newPage({viewport:{width,height:1000}});
  const today=beijingDate(),now=new Date().toISOString();
  const project={id:randomUUID(),kind:'goal',parentId:null,title:'撤回测试项目',notes:'',plannedDate:null,dueDate:null,important:true,urgent:false,order:0,completedAt:null,createdAt:now,updatedAt:now,version:0};
  const child={...project,id:randomUUID(),kind:'step',parentId:project.id,title:'保留的子任务',notes:'备注保留',plannedDate:today,focusDate:today};
  let state={revision:0,tasks:[project,child]};
  await page.route('**/api/planner',async r=>{if(r.request().method()==='POST'){const {operation}=r.request().postDataJSON();state={revision:state.revision+1,tasks:applyOperation(state.tasks,operation,state.revision+1)};}await r.fulfill({json:state});});
  await page.addInitScript(()=>localStorage.setItem('daylight.access-key','withdraw-test-key-00000000000000000'));
  await page.goto('http://127.0.0.1:5173');
  await page.getByLabel('任务操作：保留的子任务',{exact:true}).click();
  await page.getByRole('button',{name:'撤回每日计划：保留的子任务',exact:true}).click();
  await page.getByTitle('立即同步',{exact:true}).click();await page.getByText('已同步',{exact:true}).waitFor();
  await page.locator('.task-list').getByRole('button',{name:'编辑：保留的子任务',exact:true}).waitFor({state:'hidden'});
  assert.equal(state.tasks[1].plannedDate,null);
  assert.equal(state.tasks[1].focusDate,null);
  assert.equal(state.tasks[1].parentId,project.id);
  assert.equal(state.tasks[1].notes,'备注保留');
  assert.equal(state.tasks[1].completedAt,null);
  assert.equal(await page.getByRole('button',{name:'编辑：保留的子任务',exact:true}).count(),0);
  await page.getByRole('navigation').getByRole('button',{name:'项目管理',exact:true}).click();
  await page.getByRole('button',{name:'项目列表',exact:true}).click();
  await page.locator(`[data-project-id="${project.id}"] > summary`).click();
  await page.getByRole('button',{name:`加入 ${today} 每日计划：保留的子任务`,exact:true}).click();
  const withdraw=page.getByRole('button',{name:'撤回每日计划：保留的子任务',exact:true});
  await page.getByLabel('任务操作：保留的子任务',{exact:true}).click();
  await withdraw.waitFor();
  await page.getByTitle('立即同步',{exact:true}).click();await page.waitForFunction(()=>document.querySelector('.sync-status')?.textContent?.includes('已同步'));
  assert.equal(state.tasks[1].plannedDate,today);
  await page.getByLabel('任务操作：保留的子任务',{exact:true}).click();
  await withdraw.click();
  await page.getByRole('button',{name:`加入 ${today} 每日计划：保留的子任务`,exact:true}).waitFor();
  await page.getByTitle('立即同步',{exact:true}).click();await page.waitForFunction(()=>document.querySelector('.sync-status')?.textContent?.includes('已同步'));
  assert.equal(state.tasks[1].plannedDate,null);
  assert.equal(state.tasks.length,2);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  console.log(width,'withdraw from daily and project views, re-add, preserve association passed');
  await page.close();
}} finally {await browser.close();}
