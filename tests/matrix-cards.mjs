 if(cdp)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:t.x+t.width/2,y:t.y+20}]});else await page.mouse.move(t.x+t.width/2,t.y+20,{steps:12});
 await page.locator('.matrix-drag-preview').waitFor();
 if(cdp)await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});else await page.mouse.up();await page.locator('.matrix-drop-tray').waitFor({state:'hidden'});
