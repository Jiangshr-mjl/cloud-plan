 let state={revision:0,tasks:[root,child,...['确认交付内容','整理素材','归档参考'].map((title,i)=>({...child,id:randomUUID(),title,important:i===0,urgent:i<2}))]};
 await page.route('**/api/planner',async r=>{if(r.request().method()==='POST')state={revision:state.revision+1,tasks:applyOperation(state.tasks,r.request().postDataJSON().operation,state.revision+1)};await r.fulfill({json:state});});
 await page.addInitScript(()=>localStorage.setItem('daylight.access-key','matrix-cards-test-key-000000000000'));
 await page.goto('http://127.0.0.1:5173');
 await page.getByRole('navigation').getByRole('button',{name:'项目管理',exact:true}).click();
 await page.getByRole('button',{name:'子任务四象限',exact:true}).click();
 const card=page.locator('.matrix-step').first();
 assert.equal(await card.evaluate(n=>getComputedStyle(n).animationName),'task-drift');
 const motion=await page.locator('.matrix-step').evaluateAll(nodes=>nodes.map(n=>({duration:getComputedStyle(n).animationDuration,path:n.style.getPropertyValue('--drift-x0')})));
