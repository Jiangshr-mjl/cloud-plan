 await handle.scrollIntoViewIfNeeded();let box=await handle.boundingBox();
 const cdp=width===390?await page.context().newCDPSession(page):null;
 if(cdp)await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+20}]});
 else {await page.mouse.move(box.x+box.width/2,box.y+20);await page.mouse.down();}
 await page.locator('.matrix-drop-tray').waitFor();
